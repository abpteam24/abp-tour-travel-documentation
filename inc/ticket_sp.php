    <div class="abtt_doc_page_head">
        <h2>🎫 Ticket / Seat Plan Configuration</h2>
        <p class="abtt_doc_lede">
            The Ticket / Seat Plan system lets you create and manage reusable ticket types, decorative layout items
            and interactive seat plans. Build a seat plan once and assign it to multiple tours while maintaining full
            control over seat types, layout dimensions and numbering.
        </p>
    </div>

    <h3>🎫 Ticket Type Management</h3>
    <p class="abtt_doc_section_intro">
        Define reusable ticket types that can be shared across multiple tours and seat plans.
    </p>
    <ul>
        <li>Create and manage dynamic ticket types for use across tours.</li>
        <li>Define ticket names, icons, colors and ticket prefixes.</li>
        <li>Use different ticket types such as Ticket, VIP, Business Class, Special, Couple, Female, Adult, Child and Economy.</li>
        <li>Reuse the same ticket types across multiple seat plans and tours.</li>
        <li>Configure ticket types according to your booking requirements.</li>
    </ul>

    <h3>🎨 Decor Item Management</h3>
    <p class="abtt_doc_section_intro">
        Decor items represent non-seat elements of the layout — doors, aisles, windows and so on.
    </p>
    <ul>
        <li>Create and manage decorative items for seat plan layouts.</li>
        <li>Use items such as Driver Seat, Door Entry, Stairs, Aisle/Walkway, Window, Engine Box, Toilet, Luggage Rack, Food/Snacks and Emergency Exit.</li>
        <li>Arrange decorative elements to represent the real layout.</li>
        <li>Use decor items for visual organisation without treating them as passenger seats.</li>
    </ul>

    <h3>💺 Reusable Seat Plans</h3>
    <p class="abtt_doc_section_intro">
        Create a seat layout once and assign it to multiple tours. This reduces repetitive work when the same
        arrangement is shared by different events.
    </p>
    <ul>
        <li>Create and manage multiple reusable seat plans.</li>
        <li>Assign a seat plan to multiple tours.</li>
        <li>Automatically calculate the total number of available seats.</li>
        <li>Automatically identify and count assigned ticket types.</li>
        <li>View seat type quantities directly from the seat plan list.</li>
        <li>Duplicate or manage existing seat plans when needed.</li>
    </ul>

    <h3>⚙️ Seat Plan Layout Configuration</h3>
    <ul>
        <li>Define the number of rows and columns for the seat layout.</li>
        <li>Configure the seat plan background image or background color.</li>
        <li>Set individual cell width, height, gap and radius.</li>
        <li>Add or remove rows and columns according to the required layout.</li>
        <li>Create complex layouts using multiple cells for selected elements.</li>
        <li>Arrange seats and decorative items according to the real structure.</li>
    </ul>

    <h3>🪑 Seat Type Assignment</h3>
    <ul>
        <li>Select a ticket type and assign it to available seat cells.</li>
        <li>Automatically assign seat numbers according to the selected ticket type.</li>
        <li>Manage different seat categories within the same seat plan.</li>
        <li>View ticket-type-wise seat quantities while designing the layout.</li>
        <li>Select and modify individual seats or multiple cells when required.</li>
    </ul>

    <h3>🖱️ Interactive Seat Plan Editor</h3>
    <ul>
        <li>Drag cells to change their position.</li>
        <li>Drag-select multiple cells for easier layout management.</li>
        <li>Double-click to edit row/column span settings.</li>
        <li>Ctrl + Click to select a particular item or range.</li>
        <li>Shift + Click to select any range of cells.</li>
    </ul>

    <h3>🔢 Automatic Seat Numbering</h3>
    <ul>
        <li>Automatically generate seat numbers when assigning ticket types.</li>
        <li>Maintain ticket-type-specific seat numbering (e.g. VIP-01, B-01).</li>
        <li>Keep seat numbering organized across the complete seat plan.</li>
    </ul>

    <div class="abtt_doc_callout abtt_doc_callout_note">
        <strong>ℹ️ Ticket vs Seat Plan</strong>
        If you only sell by quantity, you can switch <em>Seat Plan</em> OFF in <em>Configuration → ON/OFF</em> and use
        <strong>Ticket Types</strong> alone for general-admission tours.
    </div>

